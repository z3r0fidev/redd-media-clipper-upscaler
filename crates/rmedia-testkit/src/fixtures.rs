//! The fixture catalog: every synthetic source the tests use, as FFmpeg lavfi recipes.

/// Fixture kinds (research.md R10).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Fixture {
    /// 320x240 @ 25 fps, 60 s, keyframe every 2.000 s, B-frames, sine AAC audio.
    Gop50Mp4,
    /// 1920x1080 @ 30 fps, 60 s, keyframe every 2 s (for SC-001 timing).
    Hd60Mp4,
    /// MKV with 2 audio tracks and an SRT subtitle, 20 s.
    MultiMkv,
    /// VP9/Opus WebM, 10 s.
    SmallWebm,
    /// Video only, 10 s.
    NoAudioMp4,
    /// Variable frame rate MP4, ~20 s.
    VfrMp4,
    /// MPEG-TS whose timestamps start at 10 s.
    OffsetTs,
    /// Audio with cover art (not a video).
    CoverArtM4a,
    /// An MPEG-TS stream misnamed `.mp4` (approximate seeking despite the extension).
    MislabelledTs,
    /// 321x241 H.264 (odd dimensions; 4:2:0 encoders need even sizes).
    OddDimsMp4,
    /// A text file named .mp4.
    FakeMp4,
    /// A JPEG named .mp4 (a still image, not a video).
    PhotoMp4,
    // --- 002 (mobile upscaling) ----------------------------------------------------------------
    /// 1080x1920 @ 30 fps, 10 s, near-lossless, BT.709-tagged: the clean reference for VMAF.
    CleanPortrait,
    /// `CleanPortrait` scaled to 480x854 and compressed hard (x264 CRF 35): same content.
    DegradedPortrait,
    /// `CleanPortrait` scaled to 360x640 and compressed hard (x264 CRF 35).
    DegradedPortrait360,
    /// 480x854 @ 30 fps, 60 s, untagged (SC-003 bench).
    Portrait480Long,
    /// 320x240, 10 s, with two chapters and a title tag.
    ChaptersMp4,
    /// 1280x720, 10 s: an 80x80 magenta marker moving right at 150 px/s on gray for 6 s, then a
    /// hard cut to a blue-gray shot with the marker still at x=1000 (research R7).
    MovingMarker,
    /// 1280x720, 6 s: two magenta markers 1000 px apart (cannot fit one portrait crop).
    FarMarkers,
    /// `TinySource` remuxed with a 90° display rotation (coded 320x240, displayed 240x320).
    Rotated90,
    /// 720x576 with SAR 64:45 (anamorphic 16:9), 5 s.
    Anamorphic,
    /// 720x576, interlaced top field first, 5 s.
    Interlaced,
    /// 640x360 10-bit HEVC tagged BT.2020 / PQ (HDR10 signalling), 3 s.
    HdrTagged,
    /// 320x240 (≤ 240 lines: "tiny"), 3 s.
    TinySource,
    /// 320x240 @ 120 fps, 5 s.
    HighFps120,
    // --- 003 (GIF export) ----------------------------------------------------------------------
    /// 1280x720 @ 30 fps, 6 s, testsrc2 with sine AAC audio (the US1 default case).
    Land6,
    /// 1280x720 @ 30 fps, 10 s of zooming mandelbrot: busy detail that is hard to fit a budget.
    Busy10,
    /// 1280x720 @ 30 fps, 6 s: a white page with a grey grid and a blue bar sliding across.
    FlatUi,
    /// 1280x720 @ 30 fps, 6 s: one flat colour with a small 8x8 block moving (tiny deltas).
    Static6,
    /// 640x360 @ 30 fps, 3 s FFV1 `yuva420p` MKV: a 480x270 picture with a transparent margin
    /// whose hidden colour is red (a flatten that ignores alpha shows red, not black).
    Alpha,
    /// 640x360 @ 30 fps, 4 s (narrower than the 720 px GIF target).
    Narrow,
    /// 1280x720 @ 30 fps, 10 s: one flat colour inside the GIF sample windows (0.5–1.5, 4.5–5.5
    /// and 8.5–9.5 s) and zooming mandelbrot between them, so the samples underestimate the
    /// full encode (the search's retry, research R5).
    HiddenBusy10,
    /// 1280x720 @ 25 fps, 30 s H.264 (x264, 2 s closed GOPs, 3 B-frames) + AAC: the smart cut
    /// eligible source (feature 004).
    SmartMp4,
    /// `SmartMp4` remuxed to MOV.
    SmartMov,
    /// `SmartMp4` remuxed to Matroska.
    SmartMkv,
    /// `SmartMp4` remuxed to MPEG-TS (its timestamps start at 1.4 s).
    SmartTs,
    /// 1280x720 @ 25 fps, 20 s H.264 Baseline (no B-frames), no audio.
    SmartBaseline,
    /// 1920x1080 @ 25 fps, 75 s H.264 (2 s closed GOPs) + AAC: the smart-cut speed bench (SC-005).
    SmartHd60,
    /// 1280x720 @ 25 fps, 10 s H.264 with open GOPs (leading pictures after each keyframe).
    OpenGop,
    /// 640x360 @ 25 fps, 6 s H.264 High 10 (`yuv420p10le`).
    High10,
    /// 640x360 @ 25 fps, 6 s HEVC (libx265).
    HevcMp4,
    /// 1280x720 @ 25 fps, 20 s H.264 made with other encoder settings (preset slow, 4 references,
    /// 5 B-frames, 2 s GOPs) + AAC: smart cut's re-encoded parts cannot copy its parameter sets.
    OtherEncoder,
    // --- 005 (budgeted Reddit video) ---------------------------------------------------------
    /// 1920x1080 @ 30 fps, 30 s, testsrc2 with temporal noise (a budget really binds), stereo
    /// AAC.
    FitBusy,
    /// `FitBusy` without audio.
    FitNoAudio,
    /// `FitBusy` with 5.1 audio, 10 s.
    FitSurround,
    /// `FitBusy`, 2 s.
    FitShort,
    /// 3840x2160 @ 30 fps, 2 s, testsrc2 (no noise) with stereo AAC: fitted down to 1920.
    FitUhd,
    /// 640x360 @ 30000/1001 fps (29.97), 12 s, testsrc2 with stereo AAC: a length limit is not a
    /// whole number of frames.
    FitNtsc,
}

